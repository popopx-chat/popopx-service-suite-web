const ACCENT_BAR: Record<PluginModel["accent"], string> = {
  brand: "bg-brand-soft",
  mesh: "bg-mesh-soft",
  warn: "bg-warn",
};

function PluginPanel({ model, index }: { model: PluginModel; index: number }): ReactElement {
  const { locale } = useLocale();
  const name = useCopy(model.name);
  const hook = useCopy(model.hook);
  const stateWord = useCopy(model.enabled ? ON_LABEL : OFF_LABEL);
  const shipLabel = useCopy(STATE_LABEL);
  const keysLabel = useCopy(KEYS_LABEL);
  const routeLabel = useCopy(ROUTE_LABEL);
  const fileLabel = useCopy(FILE_LABEL);
  const factsLabel = useCopy(FACT_LABEL);
  const number = String(index + 1).padStart(2, "0");

  return (
    <article
      className={`glass glass-hover relative flex flex-col overflow-hidden p-5 sm:p-6 ${model.span}`}
    >
      <span aria-hidden className={`absolute inset-x-0 top-0 h-px ${ACCENT_BAR[model.accent]} opacity-60`} />
      <header className="flex flex-wrap items-start gap-3">
        <div className="min-w-0 flex-1">
          <p className="font-mono text-[11px] tracking-[0.18em] text-faint">
            {number} / {model.code}
          </p>
          <h3 className="mt-1.5 text-[17px] font-semibold leading-snug text-white">{name}</h3>
          <p className="mt-2 text-[13.5px] leading-relaxed text-mute">{hook}</p>
        </div>
        <span className="pill shrink-0 whitespace-nowrap">
          <StatusDot tone={model.enabled ? "brand" : "warn"} pulse={model.enabled} />
          <span className="text-[11px]">
            {shipLabel} · {stateWord}
          </span>
        </span>
      </header>

      <dl className="mt-5 space-y-3">
        <p className="eyebrow">{factsLabel}</p>
        {model.facts.map((fact) => (
          <div key={pick(fact.k, locale)} className="grid grid-cols-[64px_minmax(0,1fr)] gap-3 sm:grid-cols-[80px_minmax(0,1fr)]">
            <dt className="pt-0.5 text-[11.5px] font-medium text-faint">{pick(fact.k, locale)}</dt>
            <dd className="text-[13px] leading-relaxed text-mute">{pick(fact.v, locale)}</dd>
          </div>
        ))}
      </dl>

      <div className="mt-auto pt-5">
        <p className="eyebrow">{keysLabel}</p>
        <div className="mt-2 flex flex-wrap gap-1.5">
          {model.keys.map((key) => (
            <code key={key} className="chip font-mono text-[10.5px] text-brand-soft">
              {key}
            </code>
          ))}
        </div>
        <div className="hairline-top mt-4 flex flex-wrap items-center gap-x-3 gap-y-1.5 pt-3 text-[11px] text-faint">
          <span>
            {routeLabel}
            <code className="ml-1.5 font-mono text-mesh-soft">{model.route}</code>
          </span>
          <span className="hidden sm:inline" aria-hidden>
            |
          </span>
          <span>
            {fileLabel}
            <code className="ml-1.5 font-mono">{model.file}</code>
          </span>
        </div>
      </div>
    </article>
  );
}

