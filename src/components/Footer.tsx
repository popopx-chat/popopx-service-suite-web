function LinkColumn({ id }: { id: ColumnId }): ReactElement {
  const { locale } = useLocale();
  const title = useCopy(COLUMN_TITLES[id]);

  return (
    <div>
      <h3 className="eyebrow">{title}</h3>
      <ul className="mt-4 space-y-2.5">
        {LINKS[id].map((link) => (
          <li key={`${id}-${link.href}`}>
            {link.kind === "copy" ? (
              <span className="flex flex-wrap items-center gap-2">
                <span className="text-[13px] text-mute">{pick(link.label, locale)}</span>
                <span className="font-mono text-[11.5px] text-faint">{link.href}</span>
                <CopyButton value={link.href} />
              </span>
            ) : (
              <a
                href={link.href}
                target={link.kind === "remote" ? "_blank" : undefined}
                rel={link.kind === "remote" ? "noreferrer noopener" : undefined}
                className={LINK_CLASS}
              >
                {pick(link.label, locale)}
              </a>
            )}
          </li>
        ))}
      </ul>
    </div>
  );
}

